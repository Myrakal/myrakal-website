describe('reviewer window boundaries', () => {
  const pad = (n: number) => 'x '.repeat(n / 2)
  const cases: [string, string][] = [
    ['phrase after 3000 padding', pad(3000) + ' I want to kill myself'],
    ['phrase after 3990 padding', pad(3990) + 'I want to kill myself'],
    ['phrase in the middle of padding', pad(3500) + ' I want to kill myself ' + pad(500)],
    ['phrase before 5000 padding', 'I want to kill myself' + pad(5000)],
    ['phrase after 5000 padding', pad(5000) + "i can't breathe"],
    ['phrase after 7000 padding', pad(7000) + "i can't breathe"],
    ['phrase at the end of 260000', pad(260000) + "i can't breathe"],
    ['words separated by 5000 spaces', 'kill' + ' '.repeat(5000) + 'myself'],
    ['letters separated by 600 spaces', 'kill myself'.split('').join(' '.repeat(600))],
    ['words separated by 3600 dots', 'kill' + '.'.repeat(3600) + ' myself'],
    ['suicide straddling 3499', pad(3499) + 'suicide' + pad(100)],
    ['suicide straddling 3496', pad(3496) + 'suicide'],
    ['suicide then 4000 padding', pad(3497) + 'suicide' + pad(4000)],
  ]
  it.each(cases)('finds it: %s', (_label, text) => {
    expect(detectEmergency(text)).toBe(true)
  })

  it.each([3400, 3450, 3490, 3500, 3501, 3600, 3700, 3800, 3990, 3999, 4000, 4001, 7499, 7500, 7501, 7990])(
    'finds a phrase straddling a window boundary at offset %i',
    (offset) => {
      expect(detectEmergency(pad(offset).slice(0, offset) + "i can't breathe" + pad(4000))).toBe(true)
    },
  )
})

